/**
 * Translate a UI key into the chosen language, with fallback to English
 */
export function t(key, lang = 'en') {
  const currentLangDict = translations[lang] || translations.en;
  if (currentLangDict && currentLangDict[key] !== undefined) {
    return currentLangDict[key];
  }
  return translations.en[key] || key;
}

/**
 * Simple script and keyword-based language detection
 */
export function detectLanguage(text = '') {
  if (!text || typeof text !== 'string') return 'en';
  const tStr = text.trim();

  if (/[\u0900-\u097F]/.test(tStr)) return 'hi';
  if (/[\u0600-\u06FF]/.test(tStr)) return 'ar';
  if (/[\u0980-\u09FF]/.test(tStr)) return 'bn';
  if (/[\u0B80-\u0BFF]/.test(tStr)) return 'ta';
  if (/[\u0C00-\u0C7F]/.test(tStr)) return 'te';
  if (/[\u4E00-\u9FFF]/.test(tStr)) return 'zh';
  if (/[\u3040-\u309F\u30A0-\u30FF]/.test(tStr)) return 'ja';
  if (/[\uAC00-\uD7AF]/.test(tStr)) return 'ko';
  if (/[\u0400-\u04FF]/.test(tStr)) return 'ru';

  if (/[áéíóúüñ¿¡]/i.test(tStr) || /\b(el|la|los|las|hola|gracias|amigo)\b/i.test(tStr)) return 'es';
  if (/[àâçéèêëîïôûùüÿœæ]/i.test(tStr) || /\b(le|la|les|bonjour|merci|oui)\b/i.test(tStr)) return 'fr';
  if (/[äöüß]/i.test(tStr) || /\b(der|die|das|hallo|danke|bitte)\b/i.test(tStr)) return 'de';
  if (/[ãõáéíóúçêô]/i.test(tStr) || /\b(olá|obrigado|muito)\b/i.test(tStr)) return 'pt';
  if (/\b(ciao|grazie|per favore|bene)\b/i.test(tStr)) return 'it';

  return 'en';
}

